"""Audio response validation utility for CineForge.

Provides strict real-audio validation for audio bytes and files generated by TTS
providers. Detects corrupted data, empty streams, network error pages, HTML/JSON
error responses returned with HTTP 200, and verifies audio format magic bytes.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Tuple


def is_mp3(data: bytes) -> bool:
    """Check for ID3 tag or MPEG audio sync frame."""
    if len(data) < 4:
        return False
    # ID3v2 container
    if data.startswith(b"ID3"):
        return True
    # MPEG-1/2 Audio Layer 3 frame sync: 11 bits set (0xFF followed by 0xE0 or higher)
    for i in range(min(len(data) - 1, 1024)):
        if data[i] == 0xFF and (data[i + 1] & 0xE0) == 0xE0:
            # Check layer bits (bits 17-18 of MPEG frame): layer 3 is 0b01
            layer = (data[i + 1] >> 1) & 0x03
            if layer != 0:  # Valid MPEG layer (layer 3 = 1, layer 2 = 2, layer 1 = 3)
                return True
    return False


def is_wav(data: bytes) -> bool:
    """Check for RIFF WAVE container."""
    return len(data) >= 12 and data.startswith(b"RIFF") and data[8:12] == b"WAVE"


def is_ogg(data: bytes) -> bool:
    """Check for Ogg container."""
    return len(data) >= 4 and data.startswith(b"OggS")


def is_aac_m4a(data: bytes) -> bool:
    """Check for ADTS AAC or MP4/M4A container."""
    if len(data) < 8:
        return False
    # ADTS sync word: 12 bits 0xFFF
    if data[0] == 0xFF and (data[1] & 0xF0) == 0xF0:
        return True
    # ISO base media file (ftyp)
    if data[4:8] == b"ftyp":
        return True
    return False


def is_flac(data: bytes) -> bool:
    """Check for fLaC marker."""
    return len(data) >= 4 and data.startswith(b"fLaC")


def validate_audio_bytes(data: bytes, min_bytes: int = 128) -> Tuple[bool, str, str]:
    """Validate raw audio bytes.

    Returns:
        (is_valid, format_or_error, detailed_reason)
    """
    if not isinstance(data, (bytes, bytearray)):
        return False, "invalid_type", f"Expected bytes, got {type(data).__name__}"

    if len(data) < min_bytes:
        return False, "too_small", f"Audio payload too small ({len(data)} bytes, min {min_bytes})"

    head = data[:512].strip()

    # Detect common web/API text error responses masquerading as audio
    lower_head = head.lower()
    if lower_head.startswith((b"<!doctype html", b"<html", b"<?xml", b"<error")):
        snippet = head[:120].decode("utf-8", errors="replace").strip()
        return False, "html_error", f"Received HTML error page instead of audio: {snippet}"

    if lower_head.startswith(b"{") and any(k in lower_head for k in (b'"error"', b'"detail"', b'"message"', b'"code"')):
        snippet = head[:120].decode("utf-8", errors="replace").strip()
        return False, "json_error", f"Received JSON error instead of audio: {snippet}"

    if is_wav(data):
        return True, "wav", f"Valid RIFF WAVE audio ({len(data)} bytes)"
    if is_mp3(data):
        return True, "mp3", f"Valid MPEG/ID3 MP3 audio ({len(data)} bytes)"
    if is_ogg(data):
        return True, "ogg", f"Valid Ogg Vorbis/Opus audio ({len(data)} bytes)"
    if is_aac_m4a(data):
        return True, "m4a", f"Valid AAC/M4A audio ({len(data)} bytes)"
    if is_flac(data):
        return True, "flac", f"Valid FLAC audio ({len(data)} bytes)"

    return False, "unknown_audio_format", f"Data ({len(data)} bytes) does not match recognized audio headers"


def validate_audio_file(file_path: str | Path, min_bytes: int = 128) -> Tuple[bool, str, str]:
    """Validate an audio file on disk."""
    p = Path(file_path)
    if not p.is_file():
        return False, "file_missing", f"Audio file does not exist: {p}"

    size = p.stat().st_size
    if size < min_bytes:
        return False, "file_empty", f"Audio file too small ({size} bytes, min {min_bytes})"

    try:
        with open(p, "rb") as f:
            chunk = f.read(min(size, 65536))
        return validate_audio_bytes(chunk, min_bytes=min_bytes)
    except Exception as exc:
        return False, "read_error", f"Failed to read audio file: {exc}"
